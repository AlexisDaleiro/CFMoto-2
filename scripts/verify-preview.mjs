import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { testHeaders } from './test-headers.mjs';
const base = process.env.TEST_URL;
assert.ok(base, 'TEST_URL is required');
const headers = await testHeaders(base);
const request = (url) => fetch(url, { headers });
const response = await request(base);
const html = await response.text();
assert.equal(response.status, 200, 'Preview is accessible');
assert.match(response.headers.get('x-robots-tag') || '', /noindex.*nofollow/, 'HTTP exclusion');
assert.match(html, /name="robots" content="noindex, nofollow"/, 'Metadata exclusion');
const canonical = html.match(/rel="canonical" href="([^"]+)"/)?.[1];
assert.equal(new URL(canonical).origin, new URL(base).origin, 'Preview canonical uses preview host');
const image = html.match(/property="og:image" content="([^"]+)"/)?.[1];
assert.equal((await request(image)).status, 200, 'Social image resolves');
const robots = await (await request(base + '/robots.txt')).text();
assert.ok(!/Disallow:\s*\/$/m.test(robots), 'Crawler can read noindex');
const sitemap = await (await request(base + '/sitemap.xml')).text();
assert.equal([...sitemap.matchAll(/<loc>/g)].length, 32);
assert.ok(!sitemap.includes('localhost'), 'No local URLs in sitemap');
const missing = await request(base + '/ruta-inexistente');
assert.equal(missing.status, 404);
assert.match(await missing.text(), /Este camino/);
await fs.writeFile('artifacts/preview-verification.json', JSON.stringify({ checkedAt: new Date().toISOString(), environment: base, status: 200, canonical, socialImage: image, robots, sitemapPages: 32, missingStatus: 404, indexExcluded: true }, null, 2));
console.log('PASS: preview headers, metadata, canonical, social image, crawl permissions, sitemap and custom 404.');
